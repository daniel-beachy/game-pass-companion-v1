export function canonicalTags(raw: string[]): string[] {
  const out = new Set<string>();
  for (const r of raw) {
    const k = r.toLowerCase().trim();
    for (const t of MAP[k] ?? []) out.add(t);
    if (k.includes("lego")) out.add("lego");
  }
  return [...out];
}
